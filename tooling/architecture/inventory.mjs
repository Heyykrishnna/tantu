import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../", import.meta.url);
const lines = ["# Locked technology inventory", "", "Generated by `npm run architecture:inventory` from the package manifests and lockfiles. Resolved versions describe the repository lock state, not proof of a deployed runtime. Review usage and qualification in the [architecture atlas](README.md).", ""];
for (const directory of ["frontend", "backend", "discovery"]) {
  const manifest = JSON.parse(readFileSync(new URL(`${directory}/package.json`, root), "utf8"));
  const lock = JSON.parse(readFileSync(new URL(`${directory}/package-lock.json`, root), "utf8"));
  lines.push(`## ${directory}`, "", "| Dependency | Manifest | Locked version | Scope |", "| --- | --- | --- | --- |");
  for (const scope of ["dependencies", "devDependencies"]) {
    for (const [name, requirement] of Object.entries(manifest[scope] ?? {}).sort(([a], [b]) => a.localeCompare(b))) {
      const entry = lock.packages[`node_modules/${name}`];
      if (!entry) throw new Error(`Missing locked dependency: ${directory}/${name}`);
      const version = entry.version ?? entry.resolved;
      if (!version) throw new Error(`Missing locked version: ${directory}/${name}`);
      lines.push(`| ${name} | \`${requirement}\` | ${version} | ${scope === "dependencies" ? "runtime" : "development"} |`);
    }
  }
  lines.push("");
}
writeFileSync(new URL("docs/architecture/technology.md", root), `${lines.join("\n")}\n`);
process.stdout.write("Updated locked technology inventory.\n");
